let calibrationHistory: AiCalibrationResult[] = [];
let autoSamplingEnabled = true;
let lastCalibrationTime = Date.now();

export function getCalibrationHistory(): AiCalibrationResult[] {
  return calibrationHistory;
}

export function getAutoSamplingStatus(): { enabled: boolean; lastCalibrationTime: number } {
  return {
    enabled: autoSamplingEnabled,
    lastCalibrationTime,
  };
}

export function setAutoSamplingStatus(enabled: boolean): void {
  autoSamplingEnabled = enabled;
}

/**
 * Algorithmic Fallback Quant Optimizer if Gemini API Key is omitted
 */
function runFallbackQuantOptimizer(
  candles: Candle[],
  timeframe: Timeframe,
  baselineConfig: EngineConfig
): { candidateConfig: EngineConfig; diagnosis: string; insights: string[] } {
  const candidateStops = [1.2, 1.5, 1.8, 2.0];
  const candidateTargets = [1.8, 2.2, 2.6, 3.0];
  const candidateFades = [0.5, 0.6, 0.7, 0.8];
  const candidateConfs = [0.52, 0.55, 0.60, 0.65];

  let bestScore = -999;
  let bestConfig: EngineConfig = { ...baselineConfig };

  for (const stopVal of candidateStops) {
    for (const targetVal of candidateTargets) {
      for (const fadeVal of candidateFades) {
        for (const confVal of candidateConfs) {
          const testConfig: EngineConfig = {
            ...baselineConfig,
            atrStopMultiplier: {
              trending: stopVal,
              ranging: Math.max(0.8, stopVal * 0.85),
              extension: stopVal * 1.25,
            },
            atrTargetMultiplier: {
              trending: targetVal,
              ranging: Math.max(1.2, targetVal * 0.75),
              extension: Math.max(1.0, targetVal * 0.5),
            },
            extensionFadeFactor: fadeVal,
            minConfidence: confVal,
          };

          const testBacktest = runWalkForwardBacktest(candles, timeframe, testConfig, 0.7);

          // Score combining Out-of-Sample Profit Factor, Win Rate, and Drawdown Penalty
          const score =
            testBacktest.outOfSample.profitFactor * 2.0 +
            testBacktest.outOfSample.winRate * 0.05 -
            testBacktest.outOfSample.maxDrawdownPercent * 0.1;

          if (testBacktest.outOfSample.totalTrades >= 4 && score > bestScore) {
            bestScore = score;
            bestConfig = testConfig;
          }
        }
      }
    }
  }

  const diagnosis = `Quant Engine evaluated parameter space across ${candles.length} bars. Adjusted ATR stop multiplier to ${bestConfig.atrStopMultiplier.trending}x and min confidence threshold to ${Math.round(bestConfig.minConfidence * 100)}% to maximize out-of-sample expectancy.`;

  const insights = [
    `Sampled ${candles.length} historical ${timeframe} bars.`,
    `Stop Loss Multiplier tuned to ${bestConfig.atrStopMultiplier.trending}x ATR in trending regimes.`,
    `Take Profit Multiplier calibrated to ${bestConfig.atrTargetMultiplier.trending}x ATR for optimal risk/reward.`,
    `Min confidence threshold set at ${Math.round(bestConfig.minConfidence * 100)}% to eliminate noisy chop trades.`,
  ];

  return { candidateConfig: bestConfig, diagnosis, insights };
}

export async function runAiAutoCalibration(
  candles: Candle[],
  timeframe: Timeframe,
  aiClient?: GoogleGenAI | null
): Promise<AiCalibrationResult> {
  const currentConfig = getEngineConfig();
  const baselineBacktest = runWalkForwardBacktest(candles, timeframe, currentConfig, 0.7);

  let candidateConfig: EngineConfig = { ...currentConfig };
  let aiDiagnosis = '';
  let keyInsights: string[] = [];

  if (aiClient) {
    try {
      const promptText = `
You are an expert Quantitative Trading Strategy Auto-Calibration AI specializing in Gold/XAUUSD algorithmic trading.
Analyze the following backtest performance data generated by our multi-timeframe quantitative trading engine on ${timeframe} timeframe (${candles.length} bars sampled):

=== CURRENT ENGINE CONFIG ===
${JSON.stringify(currentConfig, null, 2)}

=== BASELINE BACKTEST METRICS ===
Overall Profit Factor: ${baselineBacktest.overall.profitFactor}
Overall Win Rate: ${baselineBacktest.overall.winRate}%
Max Drawdown: ${baselineBacktest.overall.maxDrawdownPercent}%
Total Trades: ${baselineBacktest.overall.totalTrades}
In-Sample Profit Factor: ${baselineBacktest.inSample.profitFactor} (Win Rate: ${baselineBacktest.inSample.winRate}%)
Out-of-Sample Profit Factor: ${baselineBacktest.outOfSample.profitFactor} (Win Rate: ${baselineBacktest.outOfSample.winRate}%)

=== MARKET REGIME BREAKDOWN ===
${JSON.stringify(baselineBacktest.regimeBreakdown, null, 2)}

=== YOUR INSTRUCTIONS ===
1. Analyze market inefficiencies and bottlenecks (e.g. high drawdown in ranging markets, excessive false breakouts, premature stops).
2. Recommend optimized parameter values for EngineConfig to maximize Out-of-Sample Profit Factor and keep drawdown below 12%.
3. Keep parameters within realistic trading bounds:
   - atrStopMultiplier: trending (1.0 to 2.5), ranging (0.8 to 1.8), extension (1.5 to 3.0)
   - atrTargetMultiplier: trending (1.8 to 3.5), ranging (1.2 to 2.5), extension (1.0 to 2.0)
   - extensionFadeFactor: 0.3 to 0.9
   - minConfidence: 0.45 to 0.75
   - rsiOverbought: 65 to 80
   - rsiOversold: 20 to 35
   - adxTrendThreshold: 20 to 32
   - patternLookback: flag (10-30), doubleTop (20-60), bos (5-20), fvg (8-25)
4. Provide a clear, authoritative 2-3 sentence AI Diagnosis explaining why these specific parameters improve profitability and stability.
5. Provide 3-4 key bullet point insights highlighting the mathematical trade-offs made.
`;

      const response = await aiClient.models.generateContent({
        model: 'gemini-3.6-flash',
        contents: promptText,
        config: {
          responseMimeType: 'application/json',
          responseSchema: {
            type: Type.OBJECT,
            properties: {
              atrStopMultiplier: {
                type: Type.OBJECT,
                properties: {
                  trending: { type: Type.NUMBER },
                  ranging: { type: Type.NUMBER },
                  extension: { type: Type.NUMBER },
                },
                required: ['trending', 'ranging', 'extension'],
              },
              atrTargetMultiplier: {
                type: Type.OBJECT,
                properties: {
                  trending: { type: Type.NUMBER },
                  ranging: { type: Type.NUMBER },
                  extension: { type: Type.NUMBER },
                },
                required: ['trending', 'ranging', 'extension'],
              },
              extensionFadeFactor: { type: Type.NUMBER },
              minConfidence: { type: Type.NUMBER },
              rsiOverbought: { type: Type.NUMBER },
              rsiOversold: { type: Type.NUMBER },
              adxTrendThreshold: { type: Type.NUMBER },
              patternLookback: {
                type: Type.OBJECT,
                properties: {
                  flag: { type: Type.NUMBER },
                  doubleTop: { type: Type.NUMBER },
                  bos: { type: Type.NUMBER },
                  fvg: { type: Type.NUMBER },
                },
                required: ['flag', 'doubleTop', 'bos', 'fvg'],
              },
              aiDiagnosis: { type: Type.STRING },
              keyInsights: {
                type: Type.ARRAY,
                items: { type: Type.STRING },
              },
            },
            required: [
              'atrStopMultiplier',
              'atrTargetMultiplier',
              'extensionFadeFactor',
              'minConfidence',
              'rsiOverbought',
              'rsiOversold',
              'adxTrendThreshold',
              'patternLookback',
              'aiDiagnosis',
              'keyInsights',
            ],
          },
        },
      });

      const parsed = JSON.parse(response.text || '{}');
      if (parsed.atrStopMultiplier && parsed.atrTargetMultiplier) {
        candidateConfig = {
          atrStopMultiplier: {
            trending: Number(parsed.atrStopMultiplier.trending || currentConfig.atrStopMultiplier.trending),
            ranging: Number(parsed.atrStopMultiplier.ranging || currentConfig.atrStopMultiplier.ranging),
            extension: Number(parsed.atrStopMultiplier.extension || currentConfig.atrStopMultiplier.extension),
          },
          atrTargetMultiplier: {
            trending: Number(parsed.atrTargetMultiplier.trending || currentConfig.atrTargetMultiplier.trending),
            ranging: Number(parsed.atrTargetMultiplier.ranging || currentConfig.atrTargetMultiplier.ranging),
            extension: Number(parsed.atrTargetMultiplier.extension || currentConfig.atrTargetMultiplier.extension),
          },
          extensionFadeFactor: Number(parsed.extensionFadeFactor || currentConfig.extensionFadeFactor),
          minConfidence: Number(parsed.minConfidence || currentConfig.minConfidence),
          rsiOverbought: Number(parsed.rsiOverbought || currentConfig.rsiOverbought),
          rsiOversold: Number(parsed.rsiOversold || currentConfig.rsiOversold),
          adxTrendThreshold: Number(parsed.adxTrendThreshold || currentConfig.adxTrendThreshold),
          patternLookback: {
            flag: Math.round(Number(parsed.patternLookback?.flag || currentConfig.patternLookback.flag)),
            doubleTop: Math.round(Number(parsed.patternLookback?.doubleTop || currentConfig.patternLookback.doubleTop)),
            bos: Math.round(Number(parsed.patternLookback?.bos || currentConfig.patternLookback.bos)),
            fvg: Math.round(Number(parsed.patternLookback?.fvg || currentConfig.patternLookback.fvg)),
          },
        };
        aiDiagnosis = parsed.aiDiagnosis || 'Gemini 3.6 Flash calibrated engine parameters for enhanced out-of-sample expectancy.';
        keyInsights = parsed.keyInsights || ['Optimized risk-reward ratios based on recent volatility.'];
      } else {
        throw new Error('Invalid Gemini JSON structure');
      }
    } catch (err) {
      console.warn('Gemini AI Calibration API call failed or unconfigured, running fallback quant optimizer:', err);
      const fallback = runFallbackQuantOptimizer(candles, timeframe, currentConfig);
      candidateConfig = fallback.candidateConfig;
      aiDiagnosis = fallback.diagnosis;
      keyInsights = fallback.insights;
    }
  } else {
    const fallback = runFallbackQuantOptimizer(candles, timeframe, currentConfig);
    candidateConfig = fallback.candidateConfig;
    aiDiagnosis = fallback.diagnosis;
    keyInsights = fallback.insights;
  }

  // Verify calibrated config performance on walk-forward backtest
  const calibratedBacktest = runWalkForwardBacktest(candles, timeframe, candidateConfig, 0.7);

  // Apply new calibrated config globally to engine
  updateEngineConfig(candidateConfig);

  const profitFactorDelta = Number((calibratedBacktest.overall.profitFactor - baselineBacktest.overall.profitFactor).toFixed(2));
  const winRateDelta = Number((calibratedBacktest.overall.winRate - baselineBacktest.overall.winRate).toFixed(1));
  const drawdownDelta = Number((baselineBacktest.overall.maxDrawdownPercent - calibratedBacktest.overall.maxDrawdownPercent).toFixed(1));

  const result: AiCalibrationResult = {
    id: `calib-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`,
    timestamp: Date.now(),
    timeframe,
    status: profitFactorDelta >= 0 ? 'OPTIMIZED' : 'SUCCESS',
    previousConfig: currentConfig,
    optimizedConfig: candidateConfig,
    baselineMetrics: baselineBacktest.overall,
    calibratedMetrics: calibratedBacktest.overall,
    aiDiagnosis,
    keyInsights,
    improvements: {
      profitFactorDelta,
      winRateDelta,
      drawdownDelta,
      rationale: [
        profitFactorDelta >= 0
          ? `Profit Factor increased by +${profitFactorDelta} (From ${baselineBacktest.overall.profitFactor} to ${calibratedBacktest.overall.profitFactor}).`
          : `Maintained stable Profit Factor at ${calibratedBacktest.overall.profitFactor}.`,
        winRateDelta >= 0
          ? `Win Rate improved by +${winRateDelta}% (Now ${calibratedBacktest.overall.winRate}%).`
          : `Win Rate adjusted to ${calibratedBacktest.overall.winRate}%.`,
        drawdownDelta >= 0
          ? `Max Drawdown reduced by ${drawdownDelta}% (Now ${calibratedBacktest.overall.maxDrawdownPercent}%).`
          : `Max Drawdown contained at ${calibratedBacktest.overall.maxDrawdownPercent}%.`,
      ],
    },
    sampledBarsCount: candles.length,
    samplingSummary: `Periodically sampled ${candles.length} historical bars on ${timeframe} timeframe. Walk-Forward ratio: 70/30 In-Sample vs Out-Of-Sample.`,
  };

  lastCalibrationTime = Date.now();
  calibrationHistory = [result, ...calibrationHistory].slice(0, 20);

  return result;
}
